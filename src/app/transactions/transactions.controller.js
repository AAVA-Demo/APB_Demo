(function(){
'use strict';
angular.module('app.transactions').controller('TransactionController',['$scope','TransactionService','TransactionFilterFactory','AuthService','CreditCardService',function($scope,TransactionService,TransactionFilterFactory,AuthService,CreditCardService){
var vm=this;
vm.transactions=[];
vm.cards=[];
vm.selectedCard=null;
vm.pagination={currentPage:1,pageSize:20,totalRecords:0};
vm.loading=true;
vm.selectedTransaction=null;
vm.init=function(){
if(!AuthService.validateSession()){
toastr.error('Session validation failed');
return;
}
vm.loadCards();
vm.loadTransactions();
};
vm.loadCards=function(){
CreditCardService.getAllCards().then(function(cards){
vm.cards=cards;
$scope.$apply();
});
};
vm.loadTransactions=function(){
vm.loading=true;
var params={page:vm.pagination.currentPage,pageSize:vm.pagination.pageSize};
if(vm.selectedCard){
params.cardId=vm.selectedCard;
}
TransactionService.getTransactions(params).then(function(result){
vm.transactions=result.transactions||[];
vm.pagination.totalRecords=result.total||0;
vm.loading=false;
$scope.$apply();
}).catch(function(error){
toastr.error('Failed to load transactions');
vm.loading=false;
$scope.$apply();
});
};
vm.applyFilter=function(cardId){
vm.selectedCard=cardId;
vm.pagination.currentPage=1;
vm.loadTransactions();
};
vm.clearFilter=function(){
vm.selectedCard=null;
vm.pagination.currentPage=1;
vm.loadTransactions();
};
vm.showDetail=function(transaction){
vm.selectedTransaction=transaction;
};
vm.closeDetail=function(){
vm.selectedTransaction=null;
};
vm.nextPage=function(){
if(vm.pagination.currentPage*vm.pagination.pageSize<vm.pagination.totalRecords){
vm.pagination.currentPage++;
vm.loadTransactions();
}
};
vm.prevPage=function(){
if(vm.pagination.currentPage>1){
vm.pagination.currentPage--;
vm.loadTransactions();
}
};
vm.init();
}]);
})();